class CommandRunner:
    def run(
        self,
        argv: Sequence[str],
        *,
        cwd: Path | None = None,
        env: Mapping[str, str] | None = None,
        check: bool = True,
        capture_output: bool = False,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            list(argv),
            cwd=str(cwd) if cwd is not None else None,
            env=dict(env) if env is not None else None,
            check=check,
            capture_output=capture_output,
            text=True,
        )


def _run(
    runner: RunnerProtocol,
    argv: Sequence[str],
    *,
    cwd: Path | None = None,
    env: Mapping[str, str] | None = None,
    check: bool = True,
    capture_output: bool = False,
) -> subprocess.CompletedProcess[str]:
    return runner.run(argv, cwd=cwd, env=env, check=check, capture_output=capture_output)


def _wizard_owned(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8") as stream:
            return WIZARD_MARKER in stream.read(4096)
    except (OSError, UnicodeError):
        return False


def _backup_path(path: Path) -> Path:
    candidate = path.with_name(path.name + ".bak")
    index = 1
    while candidate.exists() or candidate.is_symlink():
        candidate = path.with_name(path.name + f".bak.{index}")
        index += 1
    return candidate


def atomic_write(path: str | Path, content: str, *, mode: int = 0o644, force: bool = False) -> None:
    """Atomically write one regular target, backing up only wizard files."""

    _commit_artifacts([(Path(path), content, mode)], force=force)


def _check_parent_components(path: Path, root: Path) -> None:
    """Reject symlinked components between a deployment root and a target."""

    root = root.absolute()
    parent = path.absolute().parent
    try:
        relative = parent.relative_to(root)
    except ValueError as exc:
        raise DeployError(f"deployment target escapes its root: {path}") from exc
    current = root
    for component in relative.parts:
        current /= component
        if current.is_symlink():
            raise DeployError(f"refusing symlinked parent component {current}")
        if current.exists() and not current.is_dir():
            raise DeployError(f"deployment parent is not a directory: {current}")


def _preflight_destination(path: Path, *, force: bool) -> None:
    for parent in path.parents:
        if parent.is_symlink():
            raise DeployError(f"refusing symlinked parent component {parent}")
    if path.is_symlink():
        raise DeployError(f"refusing symlink target {path}")
    if path.exists() and not path.is_file():
        raise DeployError(f"refusing non-regular target {path}")
    if path.exists():
        if not force:
            raise DeployError(f"refusing to overwrite {path}; use --force")
        if not _wizard_owned(path):
            raise DeployError(f"refusing to replace non-wizard file {path}")
        _backup_path(path)  # reserve/check the backup naming policy before writes


def _stage_artifacts(
    artifacts: Sequence[tuple[Path, str, int]], *, force: bool, root: Path | None = None
) -> list[tuple[Path, Path, bool, Path | None]]:
    paths = [path for path, _, _ in artifacts]
    if len(set(paths)) != len(paths):
        raise DeployError("duplicate deployment artifact destination")
    for path in paths:
        if root is not None:
            _check_parent_components(path, root)
        _preflight_destination(path, force=force)
    staged: list[tuple[Path, Path, bool, Path | None]] = []
    temporary_paths: list[Path] = []
    try:
        for destination, content, mode in artifacts:
            destination.parent.mkdir(parents=True, exist_ok=True)
            fd, temporary = tempfile.mkstemp(
                prefix=f".{destination.name}.", dir=destination.parent
            )
            temporary_path = Path(temporary)
            temporary_paths.append(temporary_path)
            os.fchmod(fd, mode)
            with os.fdopen(fd, "wb") as stream:
                stream.write(content.encode("utf-8"))
                stream.flush()
                os.fsync(stream.fileno())
            staged.append((destination, temporary_path, destination.exists(), None))
    except BaseException:
        for temporary in temporary_paths:
            try:
                temporary.unlink()
            except OSError:
                pass
        raise
    return staged


@dataclass
class _ArtifactRecord:
    destination: Path
    existed: bool
    backup: Path | None
    secret: bool = False


@dataclass
class _ArtifactReceipt:
    records: list[_ArtifactRecord]

    def rollback(self) -> None:
        failures: list[str] = []
        for record in reversed(self.records):
            try:
                if record.existed and record.backup is not None:
                    os.replace(record.backup, record.destination)
                elif record.destination.is_file() and not record.destination.is_symlink():
                    record.destination.unlink()
            except OSError as exc:
                failures.append(str(exc))
        if failures:
            raise DeployError(
                "artifact rollback failed; private backups were preserved: "
                + "; ".join(failures)
            )
        for record in self.records:
            if record.backup is not None and record.backup.exists():
                try:
                    record.backup.unlink()
                except OSError:
                    pass


def _private_secret_backup(path: Path, content: bytes, root: Path) -> Path:
    backup_dir = root / ".local" / "state" / "pretender" / "deploy-backups"
    _check_parent_components(backup_dir / "env", root)
    if backup_dir.is_symlink() or (backup_dir.exists() and not backup_dir.is_dir()):
        raise DeployError(f"refusing unsafe private backup directory {backup_dir}")
    backup_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(backup_dir, 0o700)
    fd, temporary = tempfile.mkstemp(prefix=".environment.", suffix=".backup", dir=backup_dir)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
    except BaseException:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            Path(temporary).unlink()
        except OSError:
            pass
        raise
    return Path(temporary)


def _commit_artifacts(
    artifacts: Sequence[tuple[Path, str, int]], *, force: bool,
    root: Path | None = None, secret_paths: set[Path] | None = None,
    secret_backup_root: Path | None = None,
) -> _ArtifactReceipt:
    staged = _stage_artifacts(artifacts, force=force, root=root)
    committed: list[_ArtifactRecord] = []
    backups: list[Path] = []
    secret_paths = secret_paths or set()
    try:
        for destination, temporary, existed, _ in staged:
            backup = None
            if existed:
                if destination in secret_paths:
                    if secret_backup_root is None:
                        raise DeployError("private secret backup root is required")
                    backup = _private_secret_backup(
                        destination, destination.read_bytes(), secret_backup_root
                    )
                else:
                    backup = _backup_path(destination)
                    shutil.copy2(destination, backup)
                backups.append(backup)
            os.replace(temporary, destination)
            committed.append(_ArtifactRecord(destination, existed, backup, destination in secret_paths))
            os.chmod(destination, next(mode for path, _, mode in artifacts if path == destination))
    except BaseException:
        try:
            _ArtifactReceipt(committed).rollback()
        except DeployError:
            raise
        for backup in backups:
            if backup.exists():
                try:
                    backup.unlink()
                except OSError:
                    pass
        for destination, temporary, _, _ in staged:
            if temporary.exists():
                try:
                    temporary.unlink()
                except OSError:
                    pass
        raise
    finally:
        for _, temporary, _, _ in staged:
            if temporary.exists():
                try:
                    temporary.unlink()
                except OSError:
                    pass
    return _ArtifactReceipt(committed)


def _write_artifacts(plan: DeploymentPlan, *, force: bool) -> _ArtifactReceipt:
    artifacts: list[tuple[Path, str, int]] = [
        (
            plan.config_path,
            render_config(plan.provider, plan.features, plan.storage_path, plan.port),
            0o644,
        ),
    ]
    if plan.target == "native":
        artifacts.append((plan.environment_path, render_systemd_environment(plan), 0o600))
    else:
        artifacts.append((plan.environment_path, render_docker_environment(plan), 0o600))
    if plan.target == "native" and not plan.venv_path.exists():
        artifacts.append((plan.venv_marker_path, f"# {WIZARD_MARKER}\n", 0o600))
    if plan.target == "native" and plan.native_service == "systemd":
        artifacts.append((plan.unit_path, render_systemd_unit(plan), 0o600))
    root = plan.project_root if plan.target in {"compose", "docker"} else plan.home
    secret_paths = {plan.environment_path}
    return _commit_artifacts(
        artifacts,
        force=force,
        root=root,
        secret_paths=secret_paths,
        secret_backup_root=plan.home,
    )


def _ensure_venv(path: Path) -> None:
    if path.is_symlink():
        raise DeployError(f"refusing symlink virtual environment {path}")
    if path.exists() and not path.is_dir():
        raise DeployError(f"virtual environment target is not a directory: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)


def _ensure_private_config_dir(plan: DeploymentPlan) -> None:
    if plan.target != "native":
        return
    directory = plan.environment_path.parent
    _check_parent_components(directory / "environment", plan.home)
    if directory.is_symlink() or (directory.exists() and not directory.is_dir()):
        raise DeployError(f"native config directory is not a private directory: {directory}")
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    if directory.is_symlink():
        raise DeployError(f"refusing symlinked native config directory {directory}")
    os.chmod(directory, 0o700)


def _ensure_private_state_dir(plan: DeploymentPlan) -> Path:
    if plan.target != "native":
        raise DeployError("native state directory requested for a Docker plan")
    state_dir = Path(plan.storage_path).parent
    shared_state_dir = _ensure_private_user_state_dir(plan.home)
    if state_dir != shared_state_dir:
        raise DeployError("native state directory is not the shared deployment state root")
    _check_parent_components(state_dir / "pretender.db", plan.home)
    return state_dir


def _ensure_private_user_state_dir(home: Path) -> Path:
    state_dir = home / ".local" / "state" / "pretender"
    _check_parent_components(state_dir / ".wizard.lock", home)
    if state_dir.is_symlink() or (state_dir.exists() and not state_dir.is_dir()):
        raise DeployError(f"private deployment state directory is unsafe: {state_dir}")
    state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    if state_dir.is_symlink():
        raise DeployError(f"refusing symlinked deployment state directory {state_dir}")
    os.chmod(state_dir, 0o700)
    return state_dir


def _secure_native_database(plan: DeploymentPlan) -> None:
    database = Path(plan.storage_path)
    for path in (database, Path(f"{database}-wal"), Path(f"{database}-shm")):
        if path.is_symlink():
            raise DeployError(f"refusing symlinked native database file {path}")
        if path.exists():
            if not path.is_file():
                raise DeployError(f"native database sidecar is not a regular file: {path}")
            os.chmod(path, 0o600)


def _run_with_umask(
    runner: RunnerProtocol,
    argv: Sequence[str],
    *,
    cwd: Path | None = None,
    env: Mapping[str, str] | None = None,
) -> Any:
    old_umask = os.umask(0o077)
    try:
        return _run(runner, argv, cwd=cwd, env=env)
    finally:
        os.umask(old_umask)


def _cleanup_new_venv(plan: DeploymentPlan, *, existed: bool, marker_existed: bool) -> None:
    if existed or plan.venv_path.is_symlink():
        return
    marker = plan.venv_marker_path
    owned_marker = marker.is_file() and _wizard_owned(marker)
    if not owned_marker:
        return
    if plan.venv_path.is_dir() and not plan.venv_path.is_symlink():
        shutil.rmtree(plan.venv_path)
    if not marker_existed and marker.is_file() and _wizard_owned(marker):
        marker.unlink()


def _preflight_venv(plan: DeploymentPlan, *, force: bool) -> None:
    marker = plan.venv_marker_path
    if plan.venv_path.is_symlink():
        raise DeployError(f"refusing symlink virtual environment {plan.venv_path}")
    if plan.venv_path.exists() and not plan.venv_path.is_dir():
        raise DeployError(f"virtual environment target is not a directory: {plan.venv_path}")
    if marker.is_symlink():
        raise DeployError(f"refusing symlink virtual environment marker {marker}")
    if plan.venv_path.exists() and (
        not marker.is_file() or not _wizard_owned(marker)
    ):
        raise DeployError("existing virtual environment is not wizard-owned")
    if not plan.venv_path.exists() and marker.exists():
        _preflight_destination(marker, force=force)


def _safe_systemd_path(path: Path) -> str:
    value = str(path.resolve())
    if not value.startswith("/"):
        raise DeployError("systemd paths must be absolute")
    if any(char.isspace() or char in "'\"\\$`" for char in value):
        raise DeployError(f"systemd path contains unsupported characters: {value}")
    return value


