_LANGUAGE = "zh"


def detect_language(environ: Mapping[str, str] | None = None) -> str:
    """Pick zh for Chinese locales, English otherwise; never raise."""

    environ = os.environ if environ is None else environ
    for name in ("PRETENDER_LANG", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = environ.get(name, "")
        if not value:
            continue
        lowered = value.lower()
        if lowered.startswith("zh") or "zh_" in lowered:
            return "zh"
        if lowered in {"c", "posix"}:
            continue
        return "en"
    return "zh"


def set_language(language: str) -> str:
    """Set the wizard language; ``auto`` resolves from the environment."""

    global _LANGUAGE
    if language == "auto":
        language = detect_language()
    if language not in MESSAGES:
        raise DeployError(f"unsupported language {language!r}")
    _LANGUAGE = language
    return _LANGUAGE


def t(key: str, **values: Any) -> str:
    """Look up a message, falling back to English and then to the key."""

    template = MESSAGES.get(_LANGUAGE, {}).get(key) or MESSAGES["en"].get(key) or key
    if not values:
        return template
    try:
        return template.format(**values)
    except (KeyError, IndexError):
        return template


class DeployError(RuntimeError):
    """An expected, user-actionable deployment error."""


@dataclass(frozen=True)
class Provider:
    base_url: str
    planner_model: str
    reply_model: str
    api_key: str
    http_loopback_confirmed: bool = False
    #: A model on the SAME base_url that accepts image input, or "" when the
    #: provider serves none. Vision is a separate capability from chat: on
    #: opencode.ai/zen, ``ling-3.0-flash-fin-free`` answers text fine and
    #: rejects images with "No endpoints found that support image input",
    #: while ``hy3-free`` accepts them.
    vision_model: str = ""
    #: An embedding model, or "" when the provider has no /embeddings
    #: endpoint at all. Without it, memory recall and expression selection
    #: fall back to FTS and record weight.
    embed_model: str = ""


@dataclass(frozen=True)
class Features:
    splitting: bool = True
    typo: bool = True
    media_enabled: bool = False
    #: The adaptive learners (expression / behavior / jargon / summary /
    #: effect). Off in the dataclass default so an empty TOML boots a bare
    #: bot; ON here, because a deployment without them has a frozen reply
    #: style and never learns how its group actually talks.
    learning: bool = True


