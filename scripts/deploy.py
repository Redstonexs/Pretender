def validate_port(value: Any) -> int:
    """Return an unprivileged TCP port, rejecting anything else."""

    if isinstance(value, bool):
        raise DeployError(t("error.port"))
    if isinstance(value, str):
        text = _text(value, "port").strip()
        if not text.isdigit():
            raise DeployError(t("error.port"))
        value = int(text)
    if not isinstance(value, int) or not 1024 <= value <= 65535:
        raise DeployError(t("error.port"))
    return value


def port_available(port: int, host: str = "127.0.0.1", *, timeout: float = 0.25) -> bool:
    """Return whether a listener could bind ``host:port`` right now."""

    port = validate_port(port)
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        sock.settimeout(timeout)
        sock.bind((host, port))
    except OSError:
        return False
    finally:
        sock.close()
    return True


def describe_port_holder(port: int, *, timeout: float = 3.0) -> str:
    """Best-effort name of whatever is listening on a port; never raises.

    A busy 3002 is the most common first-run failure, so naming the holder
    turns a dead end into an obvious next step.  Missing tooling, permission
    limits and odd output all degrade to an empty string.
    """

    try:
        port = validate_port(port)
    except DeployError:
        return ""
    executable = shutil.which("ss")
    argv = [executable, "-ltnpH"] if executable else None
    if argv is None:
        executable = shutil.which("lsof")
        if executable is None:
            return ""
        argv = [executable, "-nP", f"-iTCP:{port}", "-sTCP:LISTEN"]
    try:
        completed = subprocess.run(
            argv, capture_output=True, text=True, timeout=timeout, check=False
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    for line in (completed.stdout or "").splitlines():
        if f":{port} " not in f"{line} ":
            continue
        match = re.search(r'"([^"]{1,64})",pid=(\d{1,10})', line)
        if match:
            return f"{match.group(1)} pid={match.group(2)}"
        fields = line.split()
        if executable.endswith("lsof") and len(fields) >= 2:
            return f"{fields[0]} pid={fields[1]}"
    return ""


def _holder_suffix(port: int) -> str:
    holder = describe_port_holder(port)
    return t("port.holder", holder=holder) if holder else ""


def find_free_port(
    preferred: int = DEFAULT_PORT,
    host: str = "127.0.0.1",
    *,
    span: int = PORT_SCAN_SPAN,
) -> int:
    """Return ``preferred`` when it is free, else the next free port above it."""

    preferred = validate_port(preferred)
    for candidate in range(preferred, min(preferred + max(span, 1), 65536)):
        if port_available(candidate, host):
            return candidate
    raise DeployError(
        t("error.no_free_port", host=host, port=preferred, span=span)
    )


def check_listener(
    host: str = "127.0.0.1", port: int = DEFAULT_PORT, *, timeout: float = 0.25
) -> None:
    """Fail clearly when the reverse-WebSocket listener port is occupied."""

    if not port_available(port, host, timeout=timeout):
        raise DeployError(
            t("error.listener", host=host, port=port, holder=_holder_suffix(port))
        )


def _preflight_destinations(plan: DeploymentPlan, *, force: bool) -> None:
    root = plan.project_root if plan.target in {"compose", "docker"} else plan.home
    paths = [plan.config_path, plan.environment_path]
    if plan.target == "native":
        if not plan.venv_path.exists():
            paths.append(plan.venv_marker_path)
        if plan.native_service == "systemd":
            paths.append(plan.unit_path)
    for path in paths:
        _check_parent_components(path, root)
        _preflight_destination(path, force=force)
    if plan.target == "native":
        _check_parent_components(Path(plan.storage_path), plan.home)
        _preflight_venv(plan, force=force)


def _preflight_systemd(runner: RunnerProtocol) -> None:
    active = _run(
        runner,
        ["systemctl", "--user", "is-active", "--quiet", "pretender.service"],
        check=False,
    )
    if active.returncode == 0:
        raise DeployError("pretender.service is already active; refusing to replace it")
    enabled = _run(
        runner,
        ["systemctl", "--user", "is-enabled", "--quiet", "pretender.service"],
        check=False,
    )
    if enabled.returncode == 0:
        raise DeployError("pretender.service is already enabled; refusing to replace it")


def _wait_systemd_active(
    runner: RunnerProtocol, *, attempts: int = 3, delay: float = 0.05
) -> None:
    for attempt in range(attempts):
        active = _run(
            runner,
            ["systemctl", "--user", "is-active", "--quiet", "pretender.service"],
            check=False,
        )
        if active.returncode == 0:
            return
        if attempt + 1 < attempts:
            time.sleep(delay)
    raise DeployError("pretender.service did not become active after start")


def _preflight_docker(
    plan: DeploymentPlan,
    runner: RunnerProtocol,
    *,
    listener_checker: Callable[[], None],
) -> None:
    _run(runner, ["docker", "info"])
    running = _run(
        runner,
        ["docker", "ps", "--filter", "volume=pretender-data", "--format", "{{.Names}}"],
        capture_output=True,
    )
    if running.stdout.strip():
        raise DeployError("a running container already uses pretender-data; refusing to start")
    existing = _run(
        runner,
        ["docker", "container", "inspect", "pretender"],
        check=False,
        capture_output=True,
    )
    if existing.returncode == 0:
        raise DeployError("container named 'pretender' already exists; refusing to replace it")
    listener_checker()


class DockerDaemonLock:
    """A stopped, daemon-owned lock container held for one wizard session."""

    def __init__(self, runner: RunnerProtocol, image: str):
        self.runner = runner
        self.image = image
        self.acquired = False

    def acquire(self) -> None:
        if self.acquired:
            return
        _run(
            self.runner,
            [
                "docker", "create", "--name", WIZARD_LOCK_CONTAINER,
                "--label", WIZARD_LOCK_LABEL, "--entrypoint", "/bin/true",
                self.image,
            ],
        )
        self.acquired = True

    def release(self) -> None:
        if not self.acquired:
            return
        try:
            _run(self.runner, ["docker", "rm", WIZARD_LOCK_CONTAINER])
        finally:
            self.acquired = False


class SessionLockProtocol(Protocol):
    def acquire(self) -> None:
        ...

    def release(self) -> None:
        ...


class UserWizardLock:
    """A shared non-blocking lock for every kind of wizard session."""

    def __init__(self, plan: DeploymentPlan):
        self.plan = plan
        self.handle: Any | None = None

    def acquire(self) -> None:
        if self.handle is not None:
            return
        if fcntl is None:
            raise DeployError("native wizard locking is unavailable on this platform")
        state_dir = _ensure_private_user_state_dir(self.plan.home)
        path = self.plan.shared_lock_path
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise DeployError(f"refusing unsafe native wizard lock {path}")
        flags = os.O_CREAT | os.O_RDWR
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        fd: int | None = None
        try:
            fd = os.open(path, flags, 0o600)
            os.chmod(path, 0o600)
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except (BlockingIOError, OSError) as exc:
            if fd is not None:
                os.close(fd)
            if isinstance(exc, BlockingIOError) or getattr(exc, "errno", None) in {11, 13}:
                raise DeployError("another native deployment wizard is already running") from exc
            raise DeployError(f"cannot acquire native wizard lock: {path}") from exc
        self.handle = fd

    def release(self) -> None:
        if self.handle is None:
            return
        fd = self.handle
        self.handle = None
        try:
            assert fcntl is not None
            fcntl.flock(fd, fcntl.LOCK_UN)
        finally:
            os.close(fd)


# Kept as a source-compatible name for callers of the earlier native-only API.
NativeWizardLock = UserWizardLock


def _new_venv_staging_path(plan: DeploymentPlan) -> Path:
    parent = plan.venv_path.parent
    _check_parent_components(plan.venv_path, plan.home)
    if parent.is_symlink() or (parent.exists() and not parent.is_dir()):
        raise DeployError(f"unsafe native venv parent {parent}")
    parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(parent, 0o700)
    return Path(tempfile.mkdtemp(prefix=".venv-staging-", dir=parent))


def _remove_staging_venv(path: Path | None) -> None:
    if path is not None and path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)


def promote_venv(plan: DeploymentPlan, staging: Path) -> None:
    """Atomically promote a completed venv, preserving an old one on failure."""

    final = plan.venv_path
    if staging.is_symlink() or not staging.is_dir():
        raise DeployError("venv staging path is not a regular directory")
    previous: Path | None = None
    if final.exists() or final.is_symlink():
        if final.is_symlink() or not final.is_dir():
            raise DeployError(f"unsafe native venv target {final}")
        if not plan.venv_marker_path.is_file() or not _wizard_owned(plan.venv_marker_path):
            raise DeployError("existing virtual environment is not wizard-owned")
        previous = final.with_name(f".venv-previous-{os.getpid()}")
        suffix = 1
        while previous.exists() or previous.is_symlink():
            previous = final.with_name(f".venv-previous-{os.getpid()}-{suffix}")
            suffix += 1
        os.replace(final, previous)
    try:
        os.replace(staging, final)
    except BaseException as exc:
        if previous is not None:
            try:
                os.replace(previous, final)
            except OSError as restore_error:
                raise DeployError("venv swap failed and the old venv could not be restored") from restore_error
        raise exc


def setup_plan(
    plan: DeploymentPlan,
    *,
    runner: RunnerProtocol | None = None,
    force: bool = False,
    listener_checker: Callable[[], None] | None = None,
    docker_lock: SessionLockProtocol | None = None,
) -> DeploymentPlan:
    """Preflight and install artifacts, but never start a live process."""

    runner = runner or CommandRunner()
    listener_checker = listener_checker or (lambda: check_listener(port=plan.port))
    _preflight_destinations(plan, force=force)
    if plan.target in {"compose", "docker"}:
        _preflight_docker(plan, runner, listener_checker=listener_checker)
    else:
        if hasattr(os, "geteuid") and os.geteuid() == 0:
            raise DeployError("native deployment must not be run as root")
        if plan.native_service == "systemd":
            _preflight_systemd(runner)
        listener_checker()
    own_docker_lock = False
    staging_venv: Path | None = None
    receipt: _ArtifactReceipt | None = None
    try:
        if plan.target in {"compose", "docker"}:
            if plan.target == "compose":
                pre_env = controlled_compose_env(plan)
                _run(runner, _compose_command(plan, "pull"), cwd=plan.project_root, env=pre_env)
            else:
                _run(runner, ["docker", "pull", plan.image])
            if docker_lock is None:
                docker_lock = DockerDaemonLock(runner, plan.image)
                own_docker_lock = True
            docker_lock.acquire()
        if plan.target == "native":
            _ensure_private_state_dir(plan)
        _ensure_private_config_dir(plan)
        receipt = _write_artifacts(plan, force=force)
        if plan.target in {"compose", "docker"}:
            _run(runner, ["docker", "volume", "create", "pretender-data"])
            if plan.target == "compose":
                env = controlled_compose_env(plan)
                _run(
                    runner,
                    _compose_command(plan, "config", "--quiet"),
                    cwd=plan.project_root,
                    env=env,
                )
                _run(
                    runner,
                    _compose_command(
                        plan, "run", "--rm", "--no-deps", "pretender", "init",
                        "--config", "/config/config.toml",
                    ),
                    cwd=plan.project_root,
                    env=env,
                )
            else:
                _run(runner, docker_run_init_command(plan), cwd=plan.project_root)
        else:
            staging_venv = _new_venv_staging_path(plan)
            staging_python = staging_venv / "bin" / "python"
            _run(runner, [sys.executable, "-m", "venv", str(staging_venv)])
            _run(runner, [str(staging_python), "-m", "pip", "install", str(plan.project_root)])
            native_env = {**os.environ, LLM_ENV: plan.provider.api_key, ONEBOT_ENV: plan.onebot_token}
            _run_with_umask(
                runner, native_init_command(plan, staging_venv),
                cwd=plan.project_root, env=native_env,
            )
            _secure_native_database(plan)
            promote_venv(plan, staging_venv)
            staging_venv = None
    except BaseException:
        _remove_staging_venv(staging_venv)
        if receipt is not None:
            receipt.rollback()
        raise
    finally:
        if own_docker_lock and docker_lock is not None:
            docker_lock.release()
    return plan


def start_plan(
    plan: DeploymentPlan,
    *,
    runner: RunnerProtocol | None = None,
    listener_checker: Callable[[], None] | None = None,
    output: Callable[[str], None] = print,
) -> None:
    """Run only after the caller has obtained the second confirmation."""

    runner = runner or CommandRunner()
    listener_checker = listener_checker or (lambda: check_listener(port=plan.port))
    if plan.target in {"compose", "docker"}:
        _preflight_docker(plan, runner, listener_checker=listener_checker)
        if plan.target == "compose":
            _run(
                runner,
                _compose_command(plan, "up", "-d"),
                cwd=plan.project_root,
                env=controlled_compose_env(plan),
            )
        else:
            _run(runner, docker_run_commands(plan)[-1], cwd=plan.project_root)
        return
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        raise DeployError("native deployment must not be run as root")
    listener_checker()
    if plan.native_service == "systemd":
        _preflight_systemd(runner)
        _run(runner, ["systemctl", "--user", "daemon-reload"])
        _run(runner, ["systemctl", "--user", "enable", "pretender.service"])
        try:
            _run(runner, ["systemctl", "--user", "start", "pretender.service"])
            _wait_systemd_active(runner)
        except BaseException as start_error:
            try:
                _run(runner, ["systemctl", "--user", "disable", "pretender.service"])
            except BaseException as cleanup_error:
                raise DeployError(
                    "systemd start failed and disabling the service also failed"
                ) from cleanup_error
            raise start_error
        output(t("msg.systemd_linger"))
        return
    environment = dict(os.environ)
    environment.update({LLM_ENV: plan.provider.api_key, ONEBOT_ENV: plan.onebot_token})
    _run_with_umask(
        runner,
        [
            str(plan.venv_path / "bin" / "pretender"),
            "run",
            "--live",
            "--config",
            str(plan.config_path.resolve()),
        ],
        cwd=plan.project_root,
        env=environment,
    )


def apply_plan(
    plan: DeploymentPlan,
    *,
    runner: RunnerProtocol | None = None,
    force: bool = False,
    output: Callable[[str], None] = print,
) -> None:
    """Set up artifacts and dependencies without starting a live process."""

    runner = runner or CommandRunner()
    setup_plan(plan, runner=runner, force=force)


