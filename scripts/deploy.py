def _dotenv_value(value: str, label: str) -> str:
    value = validate_secret(value, label)
    if "\n" in value or "\r" in value or "\x00" in value:
        raise DeployError(f"{label} contains a newline or NUL")
    return value


def render_docker_environment(plan: DeploymentPlan) -> str:
    """Render the project .env without exposing it in wizard output.

    The generated config and environment use one generic LLM key name for all
    provider presets.
    """

    image = _dotenv_value(plan.image, "image")
    key = _dotenv_value(plan.provider.api_key, "LLM secret")
    token = _dotenv_value(plan.onebot_token, "OneBot secret")
    lines = [
        f"# {WIZARD_MARKER}",
        f"PRETENDER_IMAGE={image}",
        f"{LLM_ENV}={key}",
        f"{ONEBOT_ENV}={token}",
        "",
    ]
    return "\n".join(lines)


def render_systemd_environment(plan: DeploymentPlan) -> str:
    """Serialize environment values using systemd EnvironmentFile quoting."""

    values = {LLM_ENV: plan.provider.api_key, ONEBOT_ENV: plan.onebot_token}
    lines = [f"# {WIZARD_MARKER}"]
    for key, value in values.items():
        if not _ENV_KEY.fullmatch(key):
            raise DeployError(f"invalid environment variable name {key!r}")
        value = validate_secret(value, f"{key} secret")
        if "\n" in value or "\r" in value or "\x00" in value:
            raise DeployError(f"{key} contains a newline or NUL")
        lines.append(f"{key}={escape_systemd_value(value)}")
    lines.append("")
    return "\n".join(lines)


def escape_systemd_value(value: str) -> str:
    """Escape a systemd EnvironmentFile value; newline and NUL are forbidden."""

    if not isinstance(value, str):
        raise DeployError("systemd environment value must be a string")
    if "\n" in value or "\r" in value or "\x00" in value:
        raise DeployError("systemd environment values must not contain newline or NUL")
    _text(value, "systemd environment value")
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("$", "\\$")
        .replace("`", "\\`")
    )


