_LEARN_PROFILES = (
    ("expression", 1800),
    ("behavior", 3600),
    ("jargon", 3600),
    ("summary", 7200),
    ("effect", 7200),
)


def _learn_profiles(enabled: bool) -> list[str]:
    if not enabled:
        return []
    lines: list[str] = []
    for name, cadence in _LEARN_PROFILES:
        lines.append(f"[learn.profiles.{name}]")
        lines.append(f"cadence_s = {cadence}")
