def build_plan(
    target: str,
    provider: Provider,
    features: Features,
    onebot_token: str,
    *,
    project_root: str | Path | None = None,
    home: str | Path | None = None,
    image: str = DEFAULT_IMAGE,
    native_service: str = "foreground",
    port: int = DEFAULT_PORT,
) -> DeploymentPlan:
    if target not in {"compose", "docker", "native"}:
        raise DeployError("target must be compose, docker, or native")
    if native_service not in {"foreground", "systemd"}:
        raise DeployError("native service must be foreground or systemd")
    if target != "native":
        native_service = "foreground"
    provider = Provider(
        validate_base_url(
            provider.base_url, allow_http_loopback=provider.http_loopback_confirmed
        ),
        validate_model_id(provider.planner_model),
        validate_model_id(provider.reply_model),
        validate_secret(provider.api_key, "API key"),
        provider.http_loopback_confirmed,
    )
    token = validate_secret(onebot_token, "OneBot token")
    root = trusted_project_root() if project_root is None else Path(project_root)
    root = root.resolve()
    home_path = Path.home() if home is None else Path(home).resolve()
    if target == "native":
        config = home_path / ".config" / "pretender" / "config.toml"
        env = home_path / ".config" / "pretender" / "environment"
        storage = str(home_path / ".local" / "state" / "pretender" / "pretender.db")
    else:
        config = root / "config" / "config.toml"
        env = root / ".env"
        storage = "data/pretender.db"
    image = validate_image_reference(image)
    return DeploymentPlan(
        target=target,
        provider=provider,
        features=features,
        onebot_token=token,
        project_root=root,
        config_path=config,
        environment_path=env,
        storage_path=storage,
        image=image,
        native_service=native_service,
        home=home_path,
        port=validate_port(port),
    )


